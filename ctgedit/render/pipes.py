def _mix(lo: int, hi: int, pct: int) -> QtGui.QColor:
    out = []
    for s in (16, 8, 0):
        a, b = (lo >> s) & 0xFF, (hi >> s) & 0xFF
        out.append(max(0, min(255, a + int((b - a) * pct / 100))))
    return QtGui.QColor(*out)


def pipe_strokes(nodes, width: int, hilight: int, lolight: int):
    """[(QPainterPath, QPen)] in drawing order for a pipe polyline."""
    w = max(1, min(32, int(width or 1)))
    out = []
    for pen_w, off, pct in PIPE_TABLE[w]:
        # GDI covers rows [y - w//2, y + (w-1)//2]: odd widths centre on the
        # pixel (+0.5), even widths extend toward the top-left
        c = 0.5 if pen_w % 2 else 0.0
        pts = [QtCore.QPointF(x - off + c, y - off + c) for x, y in nodes]
        path = QtGui.QPainterPath(pts[0])
        for p in pts[1:]:
            path.lineTo(p)
        pen = QtGui.QPen(_mix(lolight, hilight, pct))
        pen.setWidth(pen_w)
        pen.setCapStyle(QtCore.Qt.RoundCap)
        pen.setJoinStyle(QtCore.Qt.RoundJoin)
        out.append((path, pen))
    return out
