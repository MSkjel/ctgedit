"""Regenerate requirements.lock.

python tools/lock_requirements.py            write requirements.lock
python tools/lock_requirements.py --check    exit 1 when it's out of date
"""

from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import os
import re
import sys
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(REPO, "requirements.lock")
_PIN_RX = re.compile(r"^\s*([A-Za-z0-9_.\-]+)\s*==\s*([^\s;#]+)")


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def top_level(path: str) -> list:
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            m = _PIN_RX.match(line)
            if m:
                out.append(m.group(1))
    return out


def closure(names: list) -> dict:
    """{normalised name: (distribution name, installed version)}."""
    from packaging.requirements import Requirement

    seen: dict = {}
    todo = list(names)
    while todo:
        name = todo.pop()
        key = _norm(name)
        if key in seen:
            continue
        dist = md.distribution(name)
        seen[key] = (dist.metadata["Name"], dist.version)
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker is not None and not req.marker.evaluate({"extra": ""}):
                continue
            todo.append(req.name)
    return seen


def hashes(name: str, version: str) -> list:
    url = "https://pypi.org/pypi/%s/%s/json" % (name, version)
    with urllib.request.urlopen(url, timeout=30) as resp:
        data = json.load(resp)
    return sorted({f["digests"]["sha256"] for f in data.get("urls", [])})


def render(dists: dict) -> str:
    lines = [
        "# Generated by tools/lock_requirements.py from requirements.txt -- do not edit.",
        "# Python %d.%d, %s. Install: pip install --require-hashes -r requirements.lock"
        % (sys.version_info[0], sys.version_info[1], sys.platform),
        "",
    ]
    for key in sorted(dists):
        name, version = dists[key]
        hs = hashes(name, version)
        lines.append("%s==%s%s" % (key, version, " \\" if hs else ""))
        for k, h in enumerate(hs):
            lines.append("    --hash=sha256:%s%s" % (h, " \\" if k < len(hs) - 1 else ""))
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Regenerate requirements.lock")
    ap.add_argument("--check", action="store_true", help="only report whether it is current")
    a = ap.parse_args(argv)
    text = render(closure(top_level(os.path.join(REPO, "requirements.txt"))))
    if a.check:
        try:
            current = open(LOCK, encoding="utf-8").read()
        except OSError:
            current = ""
        if current.replace("\r\n", "\n") != text:
            print("requirements.lock is out of date -- run tools/lock_requirements.py")
            return 1
        print("requirements.lock is current")
        return 0
    with open(LOCK, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s" % LOCK)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
